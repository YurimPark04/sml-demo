def _count_table(options: dict[str, Any], schema: str, table: str) -> int:
    _validate_identifier(schema, "schema")
    _validate_identifier(table, "table")
    with oracle_connection(options) as conn:
        with conn.cursor() as cursor:
            cursor.execute(f"SELECT COUNT(*) FROM {schema}.{table.upper()}")
            return int(cursor.fetchone()[0])


def _limit_query(query: str, limit: int) -> str:
    cleaned = query.strip().rstrip(";")
    if not cleaned.lower().startswith("select"):
        raise ValueError("Only SELECT queries are allowed for dataset creation.")
    return f"SELECT * FROM ({cleaned}) WHERE ROWNUM <= {int(limit)}"


def _validate_identifier(value: str, label: str) -> None:
    if not value or not _IDENTIFIER.match(value):
        raise ValueError(f"Invalid Oracle {label} identifier: {value!r}")


def _extract_table_name(statement: str) -> str:
    parts = statement.split()
    return parts[2] if len(parts) >= 3 else "UNKNOWN"


