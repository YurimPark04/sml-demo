def _materialize_selected_dataset(
    app_connection: dict[str, Any],
    dataset: dict[str, Any],
    selected_columns: list[str],
) -> str:
    """Create a DB table containing only target and active feature columns."""

    dataset_id = int(dataset["dataset_id"])
    table_name = f"SML_DS_{dataset_id}_SELECTED"
    _validate_identifier(table_name, "table")
    for column in selected_columns:
        _validate_identifier(column, "column")
    column_sql = ", ".join(column.upper() for column in selected_columns)
    source_mode = str(dataset.get("source_mode") or "").upper()

    with oracle_connection(app_connection) as conn:
        with conn.cursor() as cursor:
            try:
                cursor.execute(f"DROP TABLE {table_name} PURGE")
            except Exception as exc:
                if "ORA-00942" not in str(exc):
                    raise
            if source_mode == "TABLE":
                schema = str(dataset.get("source_schema") or "").upper()
                table = str(dataset.get("source_table") or "").upper()
                _validate_identifier(schema, "schema")
                _validate_identifier(table, "table")
                cursor.execute(
                    f"CREATE TABLE {table_name} AS SELECT {column_sql} FROM {schema}.{table}"
                )
            elif source_mode == "SQL":
                query = str(dataset.get("source_query") or "").strip().rstrip(";")
                if not query.lower().startswith("select"):
                    raise ValueError("Only SELECT queries can be materialized.")
                cursor.execute(
                    f"CREATE TABLE {table_name} AS SELECT {column_sql} FROM ({query}) src"
                )
            else:
                raise ValueError(f"Unsupported source_mode: {source_mode}.")
        conn.commit()
    return table_name


def _read_lob(value: Any) -> Any:
    """Return a plain Python value from Oracle CLOB-like values."""

    if value is None:
        return None
    if hasattr(value, "read"):
        return value.read()
    return value


def _read_json_lob(value: Any, default: Any) -> Any:
    """Decode JSON stored as CLOB, falling back to a safe default."""

    raw = _read_lob(value)
    if not raw:
        return default
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return default


def _get_datasource_secret(app_connection: dict[str, Any], datasource_id: int) -> dict[str, Any]:
    with oracle_connection(app_connection) as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT DATASOURCE_ID, DATASOURCE_NAME, HOST, PORT, SERVICE_NAME, SID,
                       USERNAME, DEFAULT_SCHEMA, PASSWORD_SECRET, THICK_MODE_YN
                FROM SML_DATASOURCE
                WHERE DATASOURCE_ID = :datasource_id
                """,
                datasource_id=datasource_id,
            )
            row = cursor.fetchone()
    if not row:
        raise ValueError(f"Datasource {datasource_id} was not found.")
    return {
        "datasource_id": row[0],
        "datasource_name": row[1],
        "host": row[2],
        "port": row[3],
        "service_name": row[4],
        "sid": row[5],
        "username": row[6],
        "schema": row[7],
        "password": row[8],
        "thick_mode": row[9] == "Y",
    }


