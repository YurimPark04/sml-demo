def initialize_metadata_store(app_connection: dict[str, Any]) -> dict[str, Any]:
    """Create SML metadata tables if they do not exist."""

    created: list[str] = []
    skipped: list[str] = []
    altered: list[str] = []
    with oracle_connection(app_connection) as conn:
        with conn.cursor() as cursor:
            for statement in DDL_STATEMENTS:
                name = _extract_table_name(statement)
                try:
                    cursor.execute(statement)
                    created.append(name)
                except Exception as exc:  # Oracle returns ORA-00955 when object exists.
                    if "ORA-00955" in str(exc):
                        skipped.append(name)
                    else:
                        raise
            for statement in INDEX_STATEMENTS:
                name = statement.split()[2]
                try:
                    cursor.execute(statement)
                    created.append(name)
                except Exception as exc:
                    if "ORA-00955" in str(exc):
                        skipped.append(name)
                    else:
                        raise
            result = _ensure_dataset_columns(cursor)
            altered.extend(result["altered"])
            skipped.extend(result["skipped"])
        conn.commit()
    return {"created": created, "skipped": skipped, "altered": altered}


def _ensure_dataset_columns(cursor: Any) -> dict[str, list[str]]:
    """Apply additive SML_DATASET schema upgrades without dropping user data."""

    altered: list[str] = []
    skipped: list[str] = []
    for column_statement, column_name in DATASET_COLUMN_UPGRADES:
        try:
            cursor.execute(column_statement)
            altered.append(column_name)
        except Exception as exc:
            if "ORA-01430" in str(exc):
                skipped.append(column_name)
            else:
                raise
    return {"altered": altered, "skipped": skipped}


