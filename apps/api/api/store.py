def initialize_metadata_store(app_connection: dict[str, Any]) -> dict[str, Any]:
    """Create SML metadata tables if they do not exist."""

    created: list[str] = []
    skipped: list[str] = []
    altered: list[str] = []
    with oracle_connection(app_connection) as conn:
        with conn.cursor() as cursor:
            for statement in DDL_STATEMENTS:
                name = _extract_table_name(statement)
                try:
                    cursor.execute(statement)
                    created.append(name)
                except Exception as exc:  # Oracle returns ORA-00955 when object exists.
                    if "ORA-00955" in str(exc):
                        skipped.append(name)
                    else:
                        raise
            for statement in INDEX_STATEMENTS:
                name = statement.split()[2]
                try:
                    cursor.execute(statement)
                    created.append(name)
                except Exception as exc:
                    if "ORA-00955" in str(exc):
                        skipped.append(name)
                    else:
                        raise
            for column_statement, column_name in [
                ("ALTER TABLE SML_DATASET ADD ALGORITHM_NAME VARCHAR2(100)", "ALGORITHM_NAME"),
                ("ALTER TABLE SML_DATASET ADD LIBRARY_NAME VARCHAR2(100)", "LIBRARY_NAME"),
            ]:
                try:
                    cursor.execute(column_statement)
                    altered.append(column_name)
                except Exception as exc:
                    if "ORA-01430" in str(exc):
                        skipped.append(column_name)
                    else:
                        raise
        conn.commit()
    return {"created": created, "skipped": skipped, "altered": altered}


def create_demo_source_data(app_connection: dict[str, Any]) -> dict[str, Any]:
    """Create a small Oracle source table so the dataset flow can run end to end."""

    table_name = "CUSTOMER_TXN_2024Q4"
    with oracle_connection(app_connection) as conn:
        with conn.cursor() as cursor:
            try:
                cursor.execute(
                    """
                    CREATE TABLE CUSTOMER_TXN_2024Q4 (
                        CUSTOMER_ID     NUMBER PRIMARY KEY,
                        AGE             NUMBER,
                        TENURE_MONTHS   NUMBER,
                        MONTHLY_FEE     NUMBER(10, 2),
                        TOTAL_AMOUNT    NUMBER(12, 2),
                        TXN_COUNT       NUMBER,
                        REGION          VARCHAR2(30),
                        PRODUCT_TYPE    VARCHAR2(30),
                        CHURN           NUMBER(1)
                    )
                    """
                )
            except Exception as exc:
                if "ORA-00955" not in str(exc):
                    raise
            cursor.execute("SELECT COUNT(*) FROM CUSTOMER_TXN_2024Q4")
            current_rows = int(cursor.fetchone()[0])
            if current_rows == 0:
                rows = _demo_customer_rows()
                cursor.executemany(
                    """
                    INSERT INTO CUSTOMER_TXN_2024Q4 (
                        CUSTOMER_ID, AGE, TENURE_MONTHS, MONTHLY_FEE, TOTAL_AMOUNT,
                        TXN_COUNT, REGION, PRODUCT_TYPE, CHURN
                    )
                    VALUES (
                        :customer_id, :age, :tenure_months, :monthly_fee, :total_amount,
                        :txn_count, :region, :product_type, :churn
                    )
                    """,
                    rows,
                )
                current_rows = len(rows)
        conn.commit()
    return {"table": table_name, "rows": current_rows}


def register_datasource(app_connection: dict[str, Any], datasource: dict[str, Any]) -> dict[str, Any]:
    """Persist an Oracle datasource connection in SML_DATASOURCE."""

    payload = {
        "datasource_name": datasource["datasource_name"],
        "source_type": "ORACLE",
        "db_kind": datasource.get("db_kind", "ORACLE"),
        "host": datasource["host"],
        "port": int(datasource.get("port", 1521)),
        "service_name": datasource.get("service_name"),
        "sid": datasource.get("sid"),
        "username": datasource["username"],
        "default_schema": datasource.get("schema") or datasource.get("default_schema") or datasource["username"],
        "password_secret": datasource.get("password") or datasource.get("password_secret"),
        "thick_mode_yn": "Y" if datasource.get("thick_mode") else "N",
        "description": datasource.get("description"),
        "created_by": datasource.get("created_by", "demo-user"),
    }
    if not payload["service_name"] and not payload["sid"]:
        raise ValueError("service_name or sid is required.")
    with oracle_connection(app_connection) as conn:
        with conn.cursor() as cursor:
            datasource_id = cursor.var(int)
            cursor.execute(
                """
                INSERT INTO SML_DATASOURCE (
                    DATASOURCE_NAME, SOURCE_TYPE, DB_KIND, HOST, PORT, SERVICE_NAME, SID,
                    USERNAME, DEFAULT_SCHEMA, PASSWORD_SECRET, THICK_MODE_YN, DESCRIPTION, CREATED_BY
                )
                VALUES (
                    :datasource_name, :source_type, :db_kind, :host, :port, :service_name, :sid,
                    :username, :default_schema, :password_secret, :thick_mode_yn, :description, :created_by
                )
                RETURNING DATASOURCE_ID INTO :datasource_id
                """,
                {**payload, "datasource_id": datasource_id},
            )
        conn.commit()
    return {"datasource_id": int(datasource_id.getvalue()[0]), **_public_datasource(payload)}


def list_datasources(app_connection: dict[str, Any]) -> dict[str, Any]:
    """Return registered datasources without exposing stored passwords."""

