def get_dataset_process_data(
    app_connection: dict[str, Any],
    dataset_id: int,
    preview_rows: int = 200,
) -> dict[str, Any]:
    """Return dataset metadata and a scrollable preview for the process page."""

    dataset = _get_dataset_record(app_connection, dataset_id)
    if not dataset.get("datasource_id"):
        return {"dataset": dataset, "metadata": dataset.get("metadata", {})}

    datasource = _get_datasource_secret(app_connection, int(dataset["datasource_id"]))
    source_options = _source_options(datasource)
    source_mode = str(dataset["source_mode"]).upper()
    if source_mode == "TABLE":
        connector = OracleConnector(
            **source_options,
            schema=dataset["source_schema"],
            table=dataset["source_table"],
            limit=preview_rows,
        )
    elif source_mode == "SQL":
        connector = OracleConnector(**source_options, query=_limit_query(dataset["source_query"], preview_rows))
    else:
        raise ValueError(f"Unsupported source_mode: {source_mode}.")

    df = connector.load()
    metadata = build_metadata(df, preview_rows=preview_rows)
    dataset["metadata"] = metadata
    return {"dataset": dataset, "metadata": metadata}


def save_dataset_selection(app_connection: dict[str, Any], request: dict[str, Any]) -> dict[str, Any]:
    """Persist target, feature, PK, and unused column selections for the next steps."""

    dataset_id = int(request["dataset_id"])
    targets = list(request.get("target_columns") or [])
    pk_columns = list(request.get("pk_columns") or [])
    unused_columns = list(request.get("unused_columns") or [])
    feature_columns = list(request.get("feature_columns") or [])
    dataset = _get_dataset_record(app_connection, dataset_id)
    if not feature_columns:
        metadata = dataset.get("metadata", {})
        all_columns = [column["name"] for column in metadata.get("columns", [])]
        excluded = set(targets + pk_columns + unused_columns)
        feature_columns = [name for name in all_columns if name not in excluded]

    selection_profile = {
        "target_columns": targets,
        "feature_columns": feature_columns,
        "pk_columns": pk_columns,
        "unused_columns": unused_columns,
        "target_profile": request.get("target_profile") or {},
    }
    selected_columns = list(dict.fromkeys(targets + feature_columns))
    if not selected_columns:
        raise ValueError("At least one target or feature column is required.")
    selected_table_name = _materialize_selected_dataset(app_connection, dataset, selected_columns)
    selection_profile["selected_table_name"] = selected_table_name
    metadata_json = dataset.get("metadata", {}) or {}
    metadata_json["selection"] = selection_profile

    with oracle_connection(app_connection) as conn:
        with conn.cursor() as cursor:
            _ensure_dataset_columns(cursor)
            cursor.execute(
                """
                UPDATE SML_DATASET
                SET TARGET_COLUMNS = :target_columns,
                    FEATURE_COLUMNS = :feature_columns,
                    PK_COLUMNS = :pk_columns,
                    UNUSED_COLUMNS = :unused_columns,
                    SELECTED_TABLE_NAME = :selected_table_name,
                    METADATA_JSON = :metadata_json,
                    UPDATED_AT = SYSTIMESTAMP
                WHERE DATASET_ID = :dataset_id
                """,
                {
                    "target_columns": json.dumps(targets, ensure_ascii=False),
                    "feature_columns": json.dumps(feature_columns, ensure_ascii=False),
                    "pk_columns": json.dumps(pk_columns, ensure_ascii=False),
                    "unused_columns": json.dumps(unused_columns, ensure_ascii=False),
                    "selected_table_name": selected_table_name,
                    "metadata_json": json.dumps(metadata_json, ensure_ascii=False, default=str),
                    "dataset_id": dataset_id,
                },
            )
            if cursor.rowcount == 0:
                raise ValueError(f"Dataset {dataset_id} was not found.")
        conn.commit()
    return {"dataset_id": dataset_id, **selection_profile}


