def list_datasource_tables(app_connection: dict[str, Any], datasource_id: int, schema: str | None = None) -> dict[str, Any]:
    """List source tables using a stored datasource."""

    datasource = _get_datasource_secret(app_connection, datasource_id)
    source_options = _source_options(datasource)
    schema_name = (schema or datasource["schema"]).upper()
    _validate_identifier(schema_name, "schema")
    with oracle_connection(source_options) as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT table_name, num_rows
                FROM all_tables
                WHERE owner = :owner
                ORDER BY table_name
                """,
                owner=schema_name,
            )
            tables = [{"schema": schema_name, "table": row[0], "estimated_rows": row[1]} for row in cursor.fetchall()]
    return {"datasource_id": datasource_id, "schema": schema_name, "tables": tables}


def create_dataset_from_datasource(app_connection: dict[str, Any], request: dict[str, Any]) -> dict[str, Any]:
    """Load a preview from a stored datasource and persist dataset metadata."""

    task_fields = _normalize_dataset_task_fields(request)
    datasource_id = int(request["datasource_id"])
    source_mode = request.get("source_mode", "TABLE").upper()
    datasource = _get_datasource_secret(app_connection, datasource_id)
    source_options = _source_options(datasource)
    schema = (request.get("source_schema") or datasource["schema"]).upper()
    table = request.get("source_table")
    query = request.get("source_query")
    preview_rows = int(request.get("preview_rows", 1000))

    if source_mode == "TABLE":
        if not table:
            raise ValueError("source_table is required for TABLE mode.")
        connector = OracleConnector(**source_options, schema=schema, table=table, limit=preview_rows)
        source_query = None
        row_count = _count_table(source_options, schema, table)
    elif source_mode == "SQL":
        if not query:
            raise ValueError("source_query is required for SQL mode.")
        limited_query = _limit_query(query, preview_rows)
        connector = OracleConnector(**source_options, query=limited_query)
        source_query = query
        row_count = None
    else:
        raise ValueError("source_mode must be TABLE or SQL.")

    df = connector.load()
    metadata = build_metadata(df, preview_rows=10)
    metadata_json = json.dumps(metadata, ensure_ascii=False, default=str)

    with oracle_connection(app_connection) as conn:
        with conn.cursor() as cursor:
            _ensure_dataset_columns(cursor)
            dataset_id = cursor.var(int)
            cursor.execute(
                """
                INSERT INTO SML_DATASET (
                    PROJECT_NAME, DATASET_NAME, TASK_CATEGORY, TARGET_MODE,
                    TASK_TYPE, ALGORITHM_NAME, LIBRARY_NAME, DATASOURCE_ID,
                    SOURCE_MODE, SOURCE_SCHEMA, SOURCE_TABLE, SOURCE_QUERY, STATUS,
                    ROW_COUNT, COLUMN_COUNT, METADATA_JSON, CREATED_BY
                )
                VALUES (
                    :project_name, :dataset_name, :task_category, :target_mode,
                    :task_type, :algorithm_name, :library_name, :datasource_id,
                    :source_mode, :source_schema, :source_table, :source_query, 'LOADED',
                    :row_count, :column_count, :metadata_json, :created_by
                )
                RETURNING DATASET_ID INTO :dataset_id
                """,
                {
                    "project_name": request.get("project_name"),
                    "dataset_name": request["dataset_name"],
                    "task_category": task_fields["task_category"],
                    "target_mode": task_fields["target_mode"],
                    "task_type": task_fields["task_type"],
                    "algorithm_name": request.get("algorithm_name"),
                    "library_name": request.get("library_name", "scikit-learn"),
                    "datasource_id": datasource_id,
                    "source_mode": source_mode,
                    "source_schema": schema,
                    "source_table": table.upper() if table else None,
                    "source_query": source_query,
                    "row_count": row_count or len(df),
                    "column_count": len(df.columns),
                    "metadata_json": metadata_json,
                    "created_by": request.get("created_by", "demo-user"),
                    "dataset_id": dataset_id,
                },
            )
        conn.commit()

    return {
        "dataset_id": int(dataset_id.getvalue()[0]),
        "project_name": request.get("project_name"),
        "dataset_name": request["dataset_name"],
        "task_category": task_fields["task_category"],
        "target_mode": task_fields["target_mode"],
        "task_type": task_fields["task_type"],
        "algorithm_name": request.get("algorithm_name"),
        "datasource_id": datasource_id,
        "source_schema": schema,
        "source_table": table.upper() if table else None,
        "row_count": row_count or len(df),
        "column_count": len(df.columns),
        "metadata": metadata,
    }


def _normalize_dataset_task_fields(request: dict[str, Any]) -> dict[str, str | None]:
    """Resolve UI task selections into the modeling task stored for downstream runs."""

    category = request.get("task_category")
    target_mode = request.get("target_mode")
    task_type = request.get("task_type")
    if category and target_mode:
        expected = TASK_SELECTION_MAP.get((category, target_mode))
        if not expected:
            raise ValueError(f"Unsupported task selection: {category}/{target_mode}.")
        if task_type and task_type != expected:
            raise ValueError(f"task_type must be '{expected}' for {category}/{target_mode}.")
        task_type = expected
    if not task_type:
        raise ValueError("task_type is required.")
    return {
        "task_category": category,
        "target_mode": target_mode,
        "task_type": task_type,
    }


