def _demo_customer_rows() -> list[dict[str, Any]]:
    regions = ["SEOUL", "BUSAN", "DAEGU", "INCHEON", "GWANGJU"]
    products = ["BASIC", "PLUS", "PREMIUM"]
    rows = []
    for index in range(1, 121):
        age = 22 + (index * 7) % 45
        tenure = 1 + (index * 5) % 72
        fee = 19000 + ((index * 1370) % 72000)
        txn_count = 1 + (index * 3) % 55
        total = fee * max(1, tenure) + txn_count * 820
        churn = 1 if (tenure < 10 and txn_count < 12) or index % 17 == 0 else 0
        rows.append(
            {
                "customer_id": index,
                "age": age,
                "tenure_months": tenure,
                "monthly_fee": fee,
                "total_amount": total,
                "txn_count": txn_count,
                "region": regions[index % len(regions)],
                "product_type": products[index % len(products)],
                "churn": churn,
            }
        )
    return rows
