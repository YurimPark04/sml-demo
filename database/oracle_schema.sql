-- Application metadata tables for the SML dataset workflow.
-- Run this with an application owner account, not with the read-only ML data account.

CREATE TABLE SML_DATASOURCE (
    DATASOURCE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATASOURCE_NAME    VARCHAR2(100) NOT NULL,
    SOURCE_TYPE        VARCHAR2(30) DEFAULT 'ORACLE' NOT NULL,
    DB_KIND            VARCHAR2(30) DEFAULT 'ORACLE' NOT NULL,
    HOST               VARCHAR2(255) NOT NULL,
    PORT               NUMBER DEFAULT 1521 NOT NULL,
    SERVICE_NAME       VARCHAR2(255),
    SID                VARCHAR2(255),
    USERNAME           VARCHAR2(128) NOT NULL,
    DEFAULT_SCHEMA     VARCHAR2(128),
    PASSWORD_SECRET    VARCHAR2(255),
    THICK_MODE_YN      CHAR(1) DEFAULT 'N' NOT NULL,
    DESCRIPTION        VARCHAR2(1000),
    CREATED_BY         VARCHAR2(100),
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT         TIMESTAMP
);

ALTER TABLE SML_DATASOURCE ADD CONSTRAINT CK_SML_DATASOURCE_MODE
    CHECK (THICK_MODE_YN IN ('Y', 'N'));

ALTER TABLE SML_DATASOURCE ADD CONSTRAINT CK_SML_DATASOURCE_DSN
    CHECK (SERVICE_NAME IS NOT NULL OR SID IS NOT NULL);

CREATE TABLE SML_DATASET (
    DATASET_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_NAME       VARCHAR2(150),
    DATASET_NAME       VARCHAR2(150) NOT NULL,
    TASK_CATEGORY      VARCHAR2(30),
    TARGET_MODE        VARCHAR2(30),
    TASK_TYPE          VARCHAR2(50) NOT NULL,
    ALGORITHM_NAME     VARCHAR2(100),
    LIBRARY_NAME       VARCHAR2(100),
    DATASOURCE_ID      NUMBER,
    SOURCE_MODE        VARCHAR2(20) NOT NULL,
    SOURCE_SCHEMA      VARCHAR2(128),
    SOURCE_TABLE       VARCHAR2(128),
    SOURCE_QUERY       CLOB,
    STATUS             VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
    ROW_COUNT          NUMBER,
    COLUMN_COUNT       NUMBER,
    TARGET_COLUMNS     CLOB,
    FEATURE_COLUMNS    CLOB,
    PK_COLUMNS         CLOB,
    UNUSED_COLUMNS     CLOB,
    SELECTED_TABLE_NAME VARCHAR2(128),
    METADATA_JSON      CLOB,
    CREATED_BY         VARCHAR2(100),
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT         TIMESTAMP,
    CONSTRAINT FK_SML_DATASET_DATASOURCE
        FOREIGN KEY (DATASOURCE_ID) REFERENCES SML_DATASOURCE (DATASOURCE_ID)
);

ALTER TABLE SML_DATASET ADD CONSTRAINT CK_SML_DATASET_SOURCE_MODE
    CHECK (SOURCE_MODE IN ('TABLE', 'SQL'));

ALTER TABLE SML_DATASET ADD CONSTRAINT CK_SML_DATASET_STATUS
    CHECK (STATUS IN ('DRAFT', 'LOADED', 'PREPROCESSED', 'VERSIONED', 'ERROR'));

CREATE TABLE SML_DATASET_VERSION (
    VERSION_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATASET_ID         NUMBER NOT NULL,
    VERSION_NAME       VARCHAR2(200) NOT NULL,
    ARTIFACT_PATH      VARCHAR2(1000) NOT NULL,
    METADATA_PATH      VARCHAR2(1000),
    VALIDATION_JSON    CLOB,
    CREATED_BY         VARCHAR2(100),
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_SML_DATASET_VERSION_DATASET
        FOREIGN KEY (DATASET_ID) REFERENCES SML_DATASET (DATASET_ID)
);

CREATE INDEX IX_SML_DATASOURCE_NAME ON SML_DATASOURCE (DATASOURCE_NAME);
CREATE INDEX IX_SML_DATASET_TASK ON SML_DATASET (TASK_TYPE);
CREATE INDEX IX_SML_DATASET_DATASOURCE ON SML_DATASET (DATASOURCE_ID);

